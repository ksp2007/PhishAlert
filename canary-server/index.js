/**
 * PhishAlert — Active Deception & Infrastructure Intelligence
 * Stage 1: Capture Endpoint + Event Schema + Traffic Classification Engine
 * ─────────────────────────────────────────────────────────────────────────
 * Workflow this implements:
 *   Deploy Canary → Capture Hit → Classify Traffic → Store Event → (Stage 3: Correlate)
 *
 * Design principles (locked from spec):
 *   - Never claim attacker deanonymization. Output is "infrastructure
 *     classification with confidence", never "attacker identified".
 *   - No real credentials, session cookies, or email content ever pass
 *     through this endpoint. Canaries are synthetic identifiers only.
 *   - Telemetry is only ever generated by an explicit, user-authorized
 *     "Deploy Bait" action in the extension — this endpoint is passive
 *     infrastructure, it does not send anything anywhere on its own.
 *
 * Storage: two KV namespaces (see wrangler.toml)
 *   CANARY_KV  — canary metadata + campaign index
 *   EVENT_KV   — individual telemetry events, listable by canary prefix
 *
 * Endpoints:
 *   POST /api/register                  (public, rate-limited) zero-setup: an
 *                                       extension install gets its own private key
 *   GET  /api/canary/ping               (auth) connection check
 *   POST /api/canary                    (auth) create a new canary
 *   GET  /t/:canaryId                   (public) 1x1 pixel — passive load
 *   GET  /c/:canaryId                   (public) decoy link — deliberate click
 *   GET  /api/canary/:canaryId/events   (auth) telemetry for one canary
 *   GET  /api/campaign/:campaignId      (auth) cross-canary correlation
 */

// ── Constants ────────────────────────────────────────────────────────────

const TRANSPARENT_GIF_BASE64 =
  'R0lGODlhAQABAIAAAAAAAP///ywAAAAAAQABAAACAUwAOw==';

// Known automated mail-security / proxy / scanner infrastructure.
// Matching here means "this request almost certainly did not come from
// a human reading the email" — it came from infrastructure that pre-fetches
// or scans links/images before (or instead of) a human ever sees them.
const SCANNER_UA_PATTERNS = [
  /GoogleImageProxy/i,
  /Microsoft Outlook/i,
  /ms-outlook/i,
  /Outlook-Safe-?Links?/i,
  /Barracuda/i,
  /Mimecast/i,
  /Proofpoint/i,
  /Symantec/i,
  /zscaler/i,
  /Cisco.*ESA/i,
  /MessageLabs/i,
  /Forcepoint/i,
  /Trend ?Micro/i,
  /bot|crawler|spider|scanner/i,
  /curl\//i,
  /python-requests/i,
  /Go-http-client/i,
  /okhttp/i,
  /libwww-perl/i,
  /Wget/i,
];

// Hosting / datacenter network operators. A hit from one of these is
// ambiguous on its own — it could be a scanner, OR it could be a human
// attacker deliberately operating from a rented VPS. It is a supporting
// signal, not a standalone verdict.
const HOSTING_ORG_PATTERNS = [
  /amazon/i, /aws/i, /google cloud/i, /microsoft azure/i, /azure/i,
  /digitalocean/i, /ovh/i, /hetzner/i, /linode/i, /vultr/i, /choopa/i,
  /leaseweb/i, /contabo/i, /hostinger/i, /namecheap/i, /godaddy/i,
  /alibaba/i, /tencent/i, /oracle cloud/i, /scaleway/i, /m247/i,
];

const REPEAT_BURST_WINDOW_MS = 10_000; // hits inside this window count as one burst

// Zero-setup limits (protect the shared free-tier KV quota)
const DATA_TTL_SECONDS = 30 * 24 * 3600;      // canaries + events auto-delete after 30 days
const INSTALL_TTL_SECONDS = 400 * 24 * 3600;  // an install key stays valid ~13 months
const MAX_REGISTER_PER_IP_PER_DAY = 5;
const MAX_REGISTER_GLOBAL_PER_DAY = 300;
const MAX_CANARIES_PER_INSTALL_PER_DAY = 20;
const MAX_EVENTS_PER_CANARY = 50;             // stops a hammered pixel from filling KV

// ── Utilities ────────────────────────────────────────────────────────────

function json(data, status = 200) {
  return new Response(JSON.stringify(data, null, 2), {
    status,
    headers: { 'content-type': 'application/json' },
  });
}

function unauthorized() {
  return json({ error: 'unauthorized' }, 401);
}

function notFound() {
  return json({ error: 'not_found' }, 404);
}

async function sha256Hex(text) {
  const buf = await crypto.subtle.digest('SHA-256', new TextEncoder().encode(text));
  return [...new Uint8Array(buf)].map((b) => b.toString(16).padStart(2, '0')).join('');
}

function today() {
  return new Date().toISOString().slice(0, 10);
}

// Returns true if the action is allowed (and counts it), false if the daily limit is hit.
async function allowAction(env, key, limit) {
  const current = parseInt((await env.CANARY_KV.get(key)) || '0', 10);
  if (current >= limit) return false;
  await env.CANARY_KV.put(key, String(current + 1), { expirationTtl: 90000 });
  return true;
}

/**
 * Two kinds of valid key:
 *   - admin:   the optional API_KEY secret (full access, owner of the server)
 *   - install: a "pa_..." key the extension got from /api/register. Only its
 *              SHA-256 hash is stored, and it can only see its own canaries.
 */
async function authenticate(request, env) {
  const key = request.headers.get('x-api-key') || '';
  if (!key) return null;
  if (env.API_KEY && key === env.API_KEY) return { admin: true, ownerId: 'admin' };
  if (/^pa_[0-9a-f]{64}$/.test(key)) {
    const hash = await sha256Hex(key);
    if (await env.CANARY_KV.get(`install:${hash}`)) {
      return { admin: false, ownerId: hash.slice(0, 32) };
    }
  }
  return null;
}

function newCanaryId() {
  // Short, URL-safe, unguessable. Not sequential — a scanned canary ID
  // must not let anyone enumerate or predict siblings.
  const bytes = crypto.getRandomValues(new Uint8Array(9));
  const b32 = btoa(String.fromCharCode(...bytes))
    .replace(/\+/g, 'A').replace(/\//g, 'B').replace(/=/g, '');
  return `CNR-${b32.slice(0, 12).toUpperCase()}`;
}

function newEventId() {
  return crypto.randomUUID();
}

/**
 * Cloudflare populates request.cf with network/geo metadata derived from
 * its own edge — no external IP-intelligence API call, no API key, no
 * added latency. This is the core reason this is a Worker and not a
 * generic Node server.
 */
function extractNetworkContext(request) {
  const cf = request.cf || {};
  return {
    ip: request.headers.get('cf-connecting-ip') || null,
    asn: cf.asn ?? null,
    asOrganization: cf.asOrganization ?? null,
    country: cf.country ?? null,
    region: cf.region ?? null,
    city: cf.city ?? null,
    userAgent: request.headers.get('user-agent') || '',
  };
}

// ── Classification engine ────────────────────────────────────────────────

/**
 * Classifies a single canary hit. Output is intentionally hedged —
 * a label plus a confidence, never a certainty claim. See module header
 * for why "attacker identified" is never an output of this function.
 *
 * @param {object} p
 * @param {number} p.elapsedSeconds   time since canary was deployed
 * @param {string} p.userAgent
 * @param {string|null} p.asOrganization
 * @param {boolean} p.isRepeatBurst   another hit on this canary within the burst window
 * @param {'pixel'|'link'} p.baitType
 * @returns {{classification: string, confidence: number, signals: string[]}}
 */
function classifyEvent({ elapsedSeconds, userAgent, asOrganization, isRepeatBurst, baitType }) {
  const signals = [];
  let automatedScore = 0;
  let humanScore = 0;

  const ua = userAgent || '';
  const isKnownScanner = SCANNER_UA_PATTERNS.some((p) => p.test(ua));
  const isHostingOrg = !!asOrganization && HOSTING_ORG_PATTERNS.some((p) => p.test(asOrganization));
  const looksLikeBrowser = /Mozilla\/5\.0/.test(ua) && /(Chrome|Safari|Firefox|Edg)/i.test(ua);

  // Timing
  if (elapsedSeconds < 5) {
    automatedScore += 0.45;
    signals.push('prefetch_timing_lt_5s');
  } else if (elapsedSeconds < 20) {
    automatedScore += 0.20;
    signals.push('fast_timing_lt_20s');
  } else if (elapsedSeconds > 30) {
    humanScore += 0.15;
    signals.push('human_plausible_timing');
  }

  // User-Agent
  if (isKnownScanner) {
    automatedScore += 0.50;
    signals.push('known_scanner_or_proxy_ua');
  }
  if (!ua) {
    automatedScore += 0.30;
    signals.push('empty_user_agent');
  }
  if (looksLikeBrowser && !isKnownScanner) {
    humanScore += 0.20;
    signals.push('browser_like_ua');
  }

  // Network
  if (isHostingOrg) {
    automatedScore += 0.25;
    signals.push('hosting_or_datacenter_network');
  } else if (looksLikeBrowser) {
    humanScore += 0.15;
    signals.push('non_datacenter_network');
  }

  // Behavior
  if (isRepeatBurst) {
    automatedScore += 0.30;
    signals.push('repeat_burst_pattern');
  }
  if (baitType === 'link') {
    humanScore += 0.15;
    signals.push('deliberate_link_click');
  }

  automatedScore = Math.min(1, automatedScore);
  humanScore = Math.min(1, humanScore);
  const net = humanScore - automatedScore;

  let classification;
  let confidence;

  if (automatedScore >= 0.7 && automatedScore - humanScore >= 0.4) {
    classification = 'automated_infrastructure'; // strong evidence: scanner/proxy/bot
    confidence = automatedScore;
  } else if (net <= -0.25) {
    classification = 'likely_automated';
    confidence = Math.min(0.95, automatedScore);
  } else if (net >= 0.25 && isHostingOrg) {
    // Deliberate-looking interaction, but from rented/hosted infrastructure —
    // consistent with an attacker operating from a VPS, not a corporate scanner.
    classification = 'suspicious_interaction';
    confidence = Math.min(0.9, humanScore + 0.20);
  } else if (net >= 0.25) {
    classification = 'likely_human_driven';
    confidence = Math.min(0.9, humanScore + 0.15);
  } else {
    classification = 'indeterminate';
    confidence = 0.5;
  }

  return {
    classification,
    confidence: Math.round(confidence * 100) / 100,
    signals,
  };
}

// ── KV helpers ───────────────────────────────────────────────────────────

async function getCanary(env, canaryId) {
  const raw = await env.CANARY_KV.get(`canary:${canaryId}`);
  return raw ? JSON.parse(raw) : null;
}

async function listCanaryEvents(env, canaryId) {
  const list = await env.EVENT_KV.list({ prefix: `event:${canaryId}:` });
  const events = await Promise.all(
    list.keys.map(async (k) => JSON.parse(await env.EVENT_KV.get(k.name)))
  );
  events.sort((a, b) => a.timestampMs - b.timestampMs);
  return events;
}

async function recordEvent(env, canary, baitType, ctx) {
  const now = Date.now();
  const net = extractNetworkContext(ctx.request);
  const priorEvents = await listCanaryEvents(env, canary.canaryId);
  if (priorEvents.length >= MAX_EVENTS_PER_CANARY) return null;
  const isRepeatBurst = priorEvents.some(
    (e) => now - e.timestampMs < REPEAT_BURST_WINDOW_MS
  );

  const elapsedSeconds = Math.max(0, (now - canary.createdAtMs) / 1000);
  const { classification, confidence, signals } = classifyEvent({
    elapsedSeconds,
    userAgent: net.userAgent,
    asOrganization: net.asOrganization,
    isRepeatBurst,
    baitType,
  });

  const event = {
    eventId: newEventId(),
    canaryId: canary.canaryId,
    campaignId: canary.campaignId,
    baitType,
    timestampMs: now,
    timestampIso: new Date(now).toISOString(),
    elapsedSeconds: Math.round(elapsedSeconds),
    network: {
      ip: net.ip,
      asn: net.asn,
      asOrganization: net.asOrganization,
      country: net.country,
      region: net.region,
      city: net.city,
    },
    userAgent: net.userAgent,
    classification,
    confidence,
    signals,
  };

  await env.EVENT_KV.put(
    `event:${canary.canaryId}:${now}:${event.eventId}`,
    JSON.stringify(event),
    { expirationTtl: DATA_TTL_SECONDS }
  );

  return event;
}

// ── Route handlers ───────────────────────────────────────────────────────

async function handleRegister(request, env) {
  const ip = request.headers.get('cf-connecting-ip') || 'unknown';
  const day = today();
  if (!(await allowAction(env, `rl:reg:ip:${ip}:${day}`, MAX_REGISTER_PER_IP_PER_DAY))) {
    return json({ error: 'rate_limited' }, 429);
  }
  if (!(await allowAction(env, `rl:reg:all:${day}`, MAX_REGISTER_GLOBAL_PER_DAY))) {
    return json({ error: 'rate_limited' }, 429);
  }
  const bytes = crypto.getRandomValues(new Uint8Array(32));
  const apiKey = 'pa_' + [...bytes].map((b) => b.toString(16).padStart(2, '0')).join('');
  const hash = await sha256Hex(apiKey);
  await env.CANARY_KV.put(
    `install:${hash}`,
    JSON.stringify({ createdAtMs: Date.now() }),
    { expirationTtl: INSTALL_TTL_SECONDS }
  );
  return json({ apiKey });
}

async function handlePing(request, env) {
  const auth = await authenticate(request, env);
  if (!auth) return unauthorized();
  return json({ ok: true });
}

async function handleCreateCanary(request, env) {
  const auth = await authenticate(request, env);
  if (!auth) return unauthorized();
  if (!auth.admin && !(await allowAction(env, `rl:create:${auth.ownerId}:${today()}`, MAX_CANARIES_PER_INSTALL_PER_DAY))) {
    return json({ error: 'daily_limit_reached' }, 429);
  }

  let body;
  try {
    body = await request.json();
  } catch {
    return json({ error: 'invalid_json_body' }, 400);
  }

  const { campaignId, emailId, senderDomain, riskScore, baitType } = body;
  if (!campaignId || !emailId) {
    return json({ error: 'campaignId and emailId are required' }, 400);
  }

  const canaryId = newCanaryId();
  const createdAtMs = Date.now();

  const canary = {
    canaryId,
    campaignId,
    emailId,
    senderDomain: senderDomain || null,
    riskScore: typeof riskScore === 'number' ? riskScore : null,
    baitType: baitType === 'link' ? 'link' : 'pixel',
    ownerId: auth.ownerId,
    createdAtMs,
    createdAtIso: new Date(createdAtMs).toISOString(),
    status: 'deployed',
  };

  await env.CANARY_KV.put(`canary:${canaryId}`, JSON.stringify(canary), { expirationTtl: DATA_TTL_SECONDS });
  // Secondary index so a campaign can be resolved to its canaries without
  // a full KV scan.
  await env.CANARY_KV.put(`campaign:${campaignId}:${canaryId}`, canaryId, { expirationTtl: DATA_TTL_SECONDS });

  const origin = new URL(request.url).origin;
  return json({
    canaryId,
    campaignId,
    pixelUrl: `${origin}/t/${canaryId}`,
    linkUrl: `${origin}/c/${canaryId}`,
    createdAtIso: canary.createdAtIso,
  });
}

async function handlePixelHit(request, env, canaryId) {
  const canary = await getCanary(env, canaryId);
  if (canary) {
    await recordEvent(env, canary, 'pixel', { request });
  }
  // Always return a valid pixel, even for unknown/expired canary IDs —
  // never signal to the caller whether the ID was recognized.
  const bytes = Uint8Array.from(atob(TRANSPARENT_GIF_BASE64), (c) => c.charCodeAt(0));
  return new Response(bytes, {
    status: 200,
    headers: {
      'content-type': 'image/gif',
      'cache-control': 'no-store, no-cache, must-revalidate',
    },
  });
}

async function handleLinkHit(request, env, canaryId) {
  const canary = await getCanary(env, canaryId);
  if (canary) {
    await recordEvent(env, canary, 'link', { request });
  }
  // Never reveal that this was a honeypot, and never forward the visitor
  // to the real phishing destination. A bland, generic response only.
  if (env.SAFE_REDIRECT_URL) {
    return Response.redirect(env.SAFE_REDIRECT_URL, 302);
  }
  return new Response(
    '<!doctype html><html><head><meta charset="utf-8"><title>Not Found</title></head>' +
    '<body style="font-family:sans-serif;color:#444;padding:40px">' +
    '<h1>404</h1><p>The page you requested could not be found.</p></body></html>',
    { status: 404, headers: { 'content-type': 'text/html' } }
  );
}

async function handleGetCanaryEvents(request, env, canaryId) {
  const auth = await authenticate(request, env);
  if (!auth) return unauthorized();
  const canary = await getCanary(env, canaryId);
  // A key can only read its own canaries (unknown and foreign ids look identical).
  if (!canary || (!auth.admin && canary.ownerId !== auth.ownerId)) return notFound();
  const events = await listCanaryEvents(env, canaryId);
  return json({ canary, events });
}

async function handleGetCampaign(request, env, campaignId) {
  // Cross-user correlation view: server owner only (needs the API_KEY secret).
  const auth = await authenticate(request, env);
  if (!auth || !auth.admin) return unauthorized();

  const idx = await env.CANARY_KV.list({ prefix: `campaign:${campaignId}:` });
  const canaryIds = idx.keys.map((k) => k.name.split(':').pop());
  const canaries = await Promise.all(canaryIds.map((id) => getCanary(env, id)));
  const eventsByCanary = await Promise.all(
    canaryIds.map((id) => listCanaryEvents(env, id))
  );
  const allEvents = eventsByCanary.flat();

  // Infrastructure overlap: flag IPs / ASNs seen across more than one
  // canary in this campaign. This is the "Phishing DNA" correlation hook —
  // it turns isolated canary hits into a shared-infrastructure fingerprint.
  const byIp = new Map();
  const byAsn = new Map();
  for (const e of allEvents) {
    if (e.network.ip) {
      if (!byIp.has(e.network.ip)) byIp.set(e.network.ip, new Set());
      byIp.get(e.network.ip).add(e.canaryId);
    }
    if (e.network.asn) {
      if (!byAsn.has(e.network.asn)) byAsn.set(e.network.asn, new Set());
      byAsn.get(e.network.asn).add(e.canaryId);
    }
  }
  const sharedIps = [...byIp.entries()]
    .filter(([, canarySet]) => canarySet.size > 1)
    .map(([ip, canarySet]) => ({ ip, canaryIds: [...canarySet] }));
  const sharedAsns = [...byAsn.entries()]
    .filter(([, canarySet]) => canarySet.size > 1)
    .map(([asn, canarySet]) => ({ asn, canaryIds: [...canarySet] }));

  return json({
    campaignId,
    canaryCount: canaries.length,
    eventCount: allEvents.length,
    canaries,
    infrastructureOverlap: { sharedIps, sharedAsns },
  });
}

// ── Entry point ──────────────────────────────────────────────────────────

export default {
  async fetch(request, env) {
    const url = new URL(request.url);
    const { pathname } = url;
    const method = request.method;

    try {
      if (method === 'POST' && pathname === '/api/register') {
        return await handleRegister(request, env);
      }
      if (method === 'GET' && pathname === '/api/canary/ping') {
        return await handlePing(request, env);
      }
      if (method === 'POST' && pathname === '/api/canary') {
        return await handleCreateCanary(request, env);
      }

      let m;
      if (method === 'GET' && (m = pathname.match(/^\/t\/([A-Za-z0-9-]+)$/))) {
        return await handlePixelHit(request, env, m[1]);
      }
      if (method === 'GET' && (m = pathname.match(/^\/c\/([A-Za-z0-9-]+)$/))) {
        return await handleLinkHit(request, env, m[1]);
      }
      if (method === 'GET' && (m = pathname.match(/^\/api\/canary\/([A-Za-z0-9-]+)\/events$/))) {
        return await handleGetCanaryEvents(request, env, m[1]);
      }
      if (method === 'GET' && (m = pathname.match(/^\/api\/campaign\/([A-Za-z0-9_-]+)$/))) {
        return await handleGetCampaign(request, env, m[1]);
      }

      return notFound();
    } catch (err) {
      return json({ error: 'internal_error', message: String(err) }, 500);
    }
  },
};
